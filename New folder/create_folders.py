import os

folders = {
    "producer": "This folder contains the Kafka producer. It reads the cleaned dataset and sends order events to Kafka.",
    "nifi-flow": "This folder contains the Apache NiFi ETL flow. It consumes raw events from Kafka, cleans and transforms them, then publishes cleaned events to another Kafka topic.",
    "spark-job": "This folder contains the Apache Spark Streaming job. It consumes cleaned events from Kafka, calculates preparation time, queue length, station status, and alerts.",
    "database": "This folder contains the PostgreSQL database setup. It stores processed results and alerts generated by Spark.",
    "dashboard": "This folder contains the dashboard. It displays preparation time, queue length, station status, and alerts."
}

for folder, description in folders.items():
    os.makedirs(folder, exist_ok=True)

    readme_path = os.path.join(folder, "README.txt")

    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(description + "\n")

print("Folders and README files created successfully.")